CREATE OR REPLACE FUNCTION app_private.submit_zh_vowel_internal(p_code text, p_player_token uuid, p_letter text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'app_private', 'pg_temp'
AS $function$
declare
  target_room app_private.platform_rooms%rowtype;
  player app_private.room_players%rowtype;
  s app_private.zh_game_state%rowtype;
  q app_private.zh_content_puzzles%rowtype;
  letter text := upper(trim(coalesce(p_letter,'')));
  hits integer;
  current_round_score integer;
  next_player uuid;
  event jsonb;
begin
  select * into target_room
  from app_private.platform_rooms
  where code = upper(trim(p_code))
    and game_slug = 'zakrecone-haslo'
    and status = 'active'
    and expires_at > now()
  limit 1;

  if target_room.id is null then
    raise exception 'Game not active';
  end if;

  select * into player
  from app_private.room_players
  where room_id = target_room.id and player_token = p_player_token
  limit 1;

  if player.id is null then
    raise exception 'Player not found';
  end if;

  select * into s
  from app_private.zh_game_state
  where room_id = target_room.id
  for update;

  if s.mode <> 'await_spin' or s.active_player_id <> player.id then
    raise exception 'Vowel cannot be bought now';
  end if;

  if char_length(letter) <> 1 or not app_private.zh_is_vowel(letter) then
    raise exception 'Choose a vowel';
  end if;

  if letter = any(coalesce(s.used_letters, '{}'::text[])) then
    raise exception 'Letter already used';
  end if;

  select round_score into current_round_score
  from app_private.zh_scores
  where room_id = target_room.id and player_id = player.id
  for update;

  if coalesce(current_round_score,0) < 200 then
    raise exception 'Not enough points';
  end if;

  update app_private.zh_scores
  set round_score = round_score - 200
  where room_id = target_room.id and player_id = player.id;

  select * into q
  from app_private.zh_content_puzzles
  where version_id = s.content_version_id
    and puzzle_key = s.puzzle_keys[s.puzzle_index + 1];
  if q.puzzle_key is null then raise exception 'ZH_PINNED_PUZZLE_MISSING' using errcode='22023'; end if;

  hits := app_private.zh_count_letter(q.phrase, letter);

  if hits > 0 then
    event := jsonb_build_object(
      'type','vowel','playerId',player.id,'playerName',player.display_name,
      'letter',letter,'count',hits,'cost',200,'correct',true,'at',clock_timestamp()
    );

    update app_private.zh_game_state
    set used_letters = array_append(s.used_letters, letter),
        last_event = event,
        updated_at = now()
    where room_id = target_room.id;
  else
    next_player := app_private.zh_next_player(target_room.id, player.id);
    event := jsonb_build_object(
      'type','vowel','playerId',player.id,'playerName',player.display_name,
      'letter',letter,'count',0,'cost',200,'correct',false,'at',clock_timestamp()
    );

    update app_private.zh_game_state
    set used_letters = array_append(s.used_letters, letter),
        active_player_id = next_player,
        last_event = event,
        updated_at = now()
    where room_id = target_room.id;
  end if;

  return event;
end;
$function$
