-- VA BANQUE — server-authoritative multiplayer game.
-- All critical state stays in app_private and is exposed only through narrow RPCs.

alter table app_private.platform_rooms
  drop constraint if exists platform_rooms_game_slug_check;

alter table app_private.platform_rooms
  add constraint platform_rooms_game_slug_check
  check (game_slug in (
    'co-ludzie-powiedza',
    'zakrecone-haslo',
    'pod-przykrywka',
    'akta-nocy',
    'tylko-my',
    'va-banque'
  ));

create table if not exists app_private.va_banque_questions (
  id bigint generated by default as identity primary key,
  question_key text not null unique,
  category text not null,
  prompt text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) = 4),
  correct_index smallint not null check (correct_index between 0 and 3),
  difficulty text not null check (difficulty in ('easy','medium','hard')),
  explanation text not null default ''
);

alter table app_private.va_banque_questions enable row level security;
revoke all on app_private.va_banque_questions from public, anon, authenticated;

drop policy if exists "deny direct client access" on app_private.va_banque_questions;
create policy "deny direct client access"
on app_private.va_banque_questions
for all
to anon, authenticated
using (false)
with check(false);

create table if not exists app_private.va_banque_games (
  room_id uuid primary key references app_private.platform_rooms(id) on delete cascade,
  round_index integer not null default 1,
  regular_rounds integer not null,
  phase text not null default 'intro',
  phase_deadline timestamptz not null,
  question_id bigint references app_private.va_banque_questions(id),
  previous_category text,
  used_question_ids bigint[] not null default '{}',
  winning_player_id uuid references app_private.room_players(id),
  winning_bid integer,
  tie_player_ids uuid[] not null default '{}',
  takeover_player_id uuid references app_private.room_players(id),
  takeover_risk integer,
  last_event jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (phase in (
    'intro','category','bidding','bid_reveal','tie_bid','tie_reveal',
    'question','main_result','takeover_open','takeover_question',
    'takeover_result','round_result','final_category','final_bidding',
    'final_question','final_reveal','finished'
  ))
);

