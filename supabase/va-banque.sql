create or replace function app_private.va_banque_choose_question_internal(
  p_room_id uuid,
  p_exclude_category text default null
)
returns bigint
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  v_used bigint[];
  v_id bigint;
begin
  select used_question_ids into v_used
  from app_private.va_banque_games
  where room_id=p_room_id;

  select q.id into v_id
  from app_private.va_banque_questions q
  where not (q.id = any(coalesce(v_used,'{}'::bigint[])))
    and (p_exclude_category is null or q.category <> p_exclude_category)
  order by random()
  limit 1;

  if v_id is null then
    select q.id into v_id
    from app_private.va_banque_questions q
    where not (q.id = any(coalesce(v_used,'{}'::bigint[])))
    order by random()
    limit 1;
  end if;

  if v_id is null then
    raise exception 'Question bank exhausted';
  end if;

  update app_private.va_banque_games
  set used_question_ids=array_append(used_question_ids,v_id), updated_at=now()
  where room_id=p_room_id;

  return v_id;
end;
$$;

create or replace function app_private.initialize_va_banque_internal(p_room_id uuid)
returns boolean
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  v_count integer;
  v_rounds integer;
  v_question bigint;
begin
  select count(*) into v_count
  from app_private.room_players
  where room_id=p_room_id;

  if v_count < 2 or v_count > 8 then
    return false;
  end if;

  delete from app_private.va_banque_players where room_id=p_room_id;
  delete from app_private.va_banque_games where room_id=p_room_id;

  v_rounds := case
    when v_count <= 3 then 10
    when v_count <= 5 then 9
    else 8
  end;

  insert into app_private.va_banque_games(
    room_id,round_index,regular_rounds,phase,phase_deadline
  )
  values(p_room_id,1,v_rounds,'intro',now()+interval '8 seconds');

  insert into app_private.va_banque_players(room_id,player_id,points)
  select p_room_id,p.id,2000
  from app_private.room_players p
  where p.room_id=p_room_id;

  v_question := app_private.va_banque_choose_question_internal(p_room_id,null);

  update app_private.va_banque_games
  set question_id=v_question
  where room_id=p_room_id;

  return true;
end;
$$;

