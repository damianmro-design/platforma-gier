  where room_id=p_room_id;
$$;

create or replace function app_private.va_banque_advance_round_internal(p_room_id uuid)
returns void
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  g app_private.va_banque_games%rowtype;
  q_category text;
  next_q bigint;
begin
  select * into g from app_private.va_banque_games where room_id=p_room_id for update;
  if g.room_id is null then return; end if;

  select category into q_category
  from app_private.va_banque_questions
  where id=g.question_id;

  if g.round_index >= g.regular_rounds then
    next_q := app_private.va_banque_choose_question_internal(p_room_id,q_category);

    update app_private.va_banque_players
    set final_bid=null,final_bid_locked=false,
        final_answer_index=null,final_answer_locked=false
    where room_id=p_room_id;

    update app_private.va_banque_games
    set phase='final_category',
        phase_deadline=now()+interval '4 seconds',
        previous_category=q_category,
        question_id=next_q,
        winning_player_id=null,
        winning_bid=null,
        tie_player_ids='{}',
        takeover_player_id=null,
        takeover_risk=null,
        last_event=jsonb_build_object('type','final_category'),
        updated_at=now()
    where room_id=p_room_id;
    return;
  end if;

  next_q := app_private.va_banque_choose_question_internal(p_room_id,q_category);
  perform app_private.va_banque_reset_round_players_internal(p_room_id);

  update app_private.va_banque_games
  set round_index=round_index+1,
      phase='category',
      phase_deadline=now()+interval '3 seconds',
      previous_category=q_category,
      question_id=next_q,
      winning_player_id=null,
      winning_bid=null,
      tie_player_ids='{}',
      takeover_player_id=null,
      takeover_risk=null,
      last_event=jsonb_build_object('type','new_round'),
      updated_at=now()
  where room_id=p_room_id;
end;
$$;

create or replace function app_private.va_banque_tick_internal(p_code text)
returns void
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  r app_private.platform_rooms%rowtype;
  g app_private.va_banque_games%rowtype;
  q app_private.va_banque_questions%rowtype;
  v_count integer;
  v_locked integer;
  v_max integer;
  v_tied uuid[];
  v_winner uuid;
  v_correct boolean;
  v_answer smallint;
  v_delta integer;
  v_risk integer;
  v_loop integer := 0;
begin
  select * into r
  from app_private.platform_rooms
  where code=upper(trim(p_code))
    and game_slug='va-banque'
    and status='active'
    and expires_at>now()
  limit 1;

  if r.id is null then return; end if;

  loop
    v_loop := v_loop+1;
    exit when v_loop > 12;

    select * into g
    from app_private.va_banque_games
    where room_id=r.id
    for update;

    exit when g.room_id is null or g.phase='finished';

    select * into q
    from app_private.va_banque_questions
    where id=g.question_id;

    select count(*) into v_count
    from app_private.va_banque_players
    where room_id=r.id;

    if g.phase='intro' then
      exit when g.phase_deadline>now();
      update app_private.va_banque_games
      set phase='category',phase_deadline=now()+interval '3 seconds',
          last_event=jsonb_build_object('type','category'),updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='category' then
      exit when g.phase_deadline>now();
      perform app_private.va_banque_reset_round_players_internal(r.id);
      update app_private.va_banque_games
      set phase='bidding',phase_deadline=now()+interval '12 seconds',
          last_event=jsonb_build_object('type','bidding_started'),updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='bidding' then
      select count(*) into v_locked
      from app_private.va_banque_players
      where room_id=r.id and bid_locked;

      exit when g.phase_deadline>now() and v_locked<v_count;

      update app_private.va_banque_players
      set bid=coalesce(bid,0),bid_locked=true
      where room_id=r.id and not bid_locked;

      select coalesce(max(bid),0) into v_max
      from app_private.va_banque_players
      where room_id=r.id;

      if v_max<=0 then
        update app_private.va_banque_games
        set phase='round_result',phase_deadline=now()+interval '3 seconds',
            last_event=jsonb_build_object('type','all_pass'),updated_at=now()
        where room_id=r.id;
        continue;
      end if;

      select array_agg(player_id order by player_id) into v_tied
      from app_private.va_banque_players
      where room_id=r.id and bid=v_max;

      if coalesce(array_length(v_tied,1),0)=1 then
        v_winner:=v_tied[1];
        update app_private.va_banque_games
        set winning_player_id=v_winner,winning_bid=v_max,
            tie_player_ids='{}',phase='bid_reveal',
            phase_deadline=now()+interval '3 seconds',
            last_event=jsonb_build_object('type','bid_won','playerId',v_winner,'bid',v_max),
            updated_at=now()
        where room_id=r.id;
        continue;
      end if;

      update app_private.va_banque_players
      set tie_bid=null,tie_locked=false
      where room_id=r.id and player_id=any(v_tied);

      update app_private.va_banque_games
      set winning_bid=v_max,tie_player_ids=v_tied,
          phase='tie_bid',phase_deadline=now()+interval '7 seconds',
          last_event=jsonb_build_object('type','bid_tie','bid',v_max,'players',to_jsonb(v_tied)),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='tie_bid' then
      select count(*) into v_locked
      from app_private.va_banque_players
      where room_id=r.id
        and player_id=any(g.tie_player_ids)
        and tie_locked;

      exit when g.phase_deadline>now()
        and v_locked<coalesce(array_length(g.tie_player_ids,1),0);

      update app_private.va_banque_players
      set tie_bid=coalesce(tie_bid,0),tie_locked=true
      where room_id=r.id
        and player_id=any(g.tie_player_ids)
        and not tie_locked;

      select coalesce(max(tie_bid),0) into v_max
      from app_private.va_banque_players
      where room_id=r.id and player_id=any(g.tie_player_ids);

      if v_max<=0 then
        select x into v_winner
        from unnest(g.tie_player_ids) x
        order by random()
        limit 1;
        v_max:=g.winning_bid;
      else
        select player_id into v_winner
        from app_private.va_banque_players
        where room_id=r.id
          and player_id=any(g.tie_player_ids)
          and tie_bid=v_max
        order by random()
        limit 1;
      end if;

      update app_private.va_banque_games
      set winning_player_id=v_winner,winning_bid=v_max,
          phase='tie_reveal',phase_deadline=now()+interval '2 seconds',
          last_event=jsonb_build_object('type','tie_won','playerId',v_winner,'bid',v_max),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase in ('bid_reveal','tie_reveal') then
      exit when g.phase_deadline>now();
      update app_private.va_banque_games
      set phase='question',phase_deadline=now()+interval '18 seconds',
          last_event=jsonb_build_object('type','question_started'),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='question' then
      select answer_index,answer_locked into v_answer,v_correct
      from app_private.va_banque_players
      where room_id=r.id and player_id=g.winning_player_id;

      -- v_correct temporarily carries answer_locked.
      exit when g.phase_deadline>now() and not coalesce(v_correct,false);

      if v_answer is null then
        v_correct:=false;
      else
        v_correct:=(v_answer=q.correct_index);
      end if;

      if v_correct then
        update app_private.va_banque_players
        set points=points+g.winning_bid
        where room_id=r.id and player_id=g.winning_player_id;
        v_delta:=g.winning_bid;
      else
        update app_private.va_banque_players
        set points=greatest(100,points-g.winning_bid)
        where room_id=r.id and player_id=g.winning_player_id;
        v_delta:=-g.winning_bid;
      end if;

      update app_private.va_banque_games
      set phase='main_result',phase_deadline=now()+interval '3 seconds',
          last_event=jsonb_build_object(
            'type',case when v_correct then 'main_correct' else 'main_wrong' end,
            'playerId',g.winning_player_id,'delta',v_delta,'answer',v_answer,
            'correctIndex',q.correct_index
          ),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='main_result' then
      exit when g.phase_deadline>now();

      if g.last_event->>'type'='main_correct' then
        update app_private.va_banque_games
        set phase='round_result',phase_deadline=now()+interval '2 seconds',updated_at=now()
        where room_id=r.id;
      else
        update app_private.va_banque_games
        set phase='takeover_open',phase_deadline=now()+interval '4 seconds',
            takeover_player_id=null,takeover_risk=null,
            last_event=jsonb_build_object('type','takeover_open'),
            updated_at=now()
        where room_id=r.id;
      end if;
      continue;
    end if;

    if g.phase='takeover_open' then
      exit when g.phase_deadline>now();
      update app_private.va_banque_games
      set phase='round_result',phase_deadline=now()+interval '2 seconds',
          last_event=jsonb_build_object('type','no_takeover'),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='takeover_question' then
      select answer_index,answer_locked into v_answer,v_correct
      from app_private.va_banque_players
      where room_id=r.id and player_id=g.takeover_player_id;

      exit when g.phase_deadline>now() and not coalesce(v_correct,false);

      v_correct:=(v_answer is not null and v_answer=q.correct_index);
      v_risk:=coalesce(g.takeover_risk,0);

      if v_correct then
        update app_private.va_banque_players
        set points=points+v_risk
        where room_id=r.id and player_id=g.takeover_player_id;
        v_delta:=v_risk;
      else
        update app_private.va_banque_players
        set points=greatest(100,points-v_risk)
        where room_id=r.id and player_id=g.takeover_player_id;
        v_delta:=-v_risk;
      end if;

      update app_private.va_banque_games
      set phase='takeover_result',phase_deadline=now()+interval '3 seconds',
          last_event=jsonb_build_object(
            'type',case when v_correct then 'takeover_correct' else 'takeover_wrong' end,
            'playerId',g.takeover_player_id,'delta',v_delta,'answer',v_answer,
            'correctIndex',q.correct_index
          ),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='takeover_result' then
      exit when g.phase_deadline>now();
      update app_private.va_banque_games
      set phase='round_result',phase_deadline=now()+interval '2 seconds',updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='round_result' then
      exit when g.phase_deadline>now();
      perform app_private.va_banque_advance_round_internal(r.id);
      continue;
    end if;

    if g.phase='final_category' then
      exit when g.phase_deadline>now();
      update app_private.va_banque_players
      set final_bid=null,final_bid_locked=false,
          final_answer_index=null,final_answer_locked=false
      where room_id=r.id;

      update app_private.va_banque_games
      set phase='final_bidding',phase_deadline=now()+interval '15 seconds',
          last_event=jsonb_build_object('type','final_bidding'),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='final_bidding' then
      select count(*) into v_locked
      from app_private.va_banque_players
      where room_id=r.id and final_bid_locked;

      exit when g.phase_deadline>now() and v_locked<v_count;

      update app_private.va_banque_players
      set final_bid=coalesce(final_bid,0),final_bid_locked=true
      where room_id=r.id and not final_bid_locked;

      update app_private.va_banque_games
      set phase='final_question',phase_deadline=now()+interval '20 seconds',
          last_event=jsonb_build_object('type','final_question'),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='final_question' then
      select count(*) into v_locked
      from app_private.va_banque_players
      where room_id=r.id and final_answer_locked;

      exit when g.phase_deadline>now() and v_locked<v_count;

      update app_private.va_banque_players
      set points=case
        when final_answer_locked and final_answer_index=q.correct_index
          then points+coalesce(final_bid,0)
        else greatest(0,points-coalesce(final_bid,0))
      end
      where room_id=r.id;

      update app_private.va_banque_games
      set phase='final_reveal',phase_deadline=now()+interval '6 seconds',
          last_event=jsonb_build_object('type','final_reveal','correctIndex',q.correct_index),
          updated_at=now()
      where room_id=r.id;
      continue;
    end if;

    if g.phase='final_reveal' then
      exit when g.phase_deadline>now();
      update app_private.va_banque_games
      set phase='finished',phase_deadline=now(),
          last_event=jsonb_build_object('type','finished'),updated_at=now()
      where room_id=r.id;

      update app_private.platform_rooms
      set game_phase='finished'
      where id=r.id;
      continue;
    end if;

    exit;
  end loop;
end;
$$;

create or replace function app_private.get_va_banque_state_internal(
  p_code text,
  p_player_token uuid default null,
  p_host_token uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  r app_private.platform_rooms%rowtype;
  g app_private.va_banque_games%rowtype;
  q app_private.va_banque_questions%rowtype;
  viewer app_private.room_players%rowtype;
  vp app_private.va_banque_players%rowtype;
  v_players jsonb;
  v_bids jsonb;
  v_final_answers jsonb;
  v_show_question boolean;
  v_show_solution boolean;
  v_is_host boolean := false;
begin
  perform app_private.va_banque_tick_internal(p_code);

  select * into r
  from app_private.platform_rooms
  where code=upper(trim(p_code))
    and game_slug='va-banque'
    and status='active'
    and expires_at>now()
  limit 1;

  if r.id is null then return null; end if;

  v_is_host := p_host_token is not null and r.host_token=p_host_token;

  if p_player_token is not null then
    select * into viewer
    from app_private.room_players
    where room_id=r.id and player_token=p_player_token
    limit 1;

    if viewer.id is null then
      raise exception 'Player not found';
    end if;

    update app_private.room_players
    set last_seen_at=now()
    where id=viewer.id;

    select * into vp
    from app_private.va_banque_players
    where room_id=r.id and player_id=viewer.id;
  elsif not v_is_host then
    raise exception 'Access denied';
  end if;

  select * into g from app_private.va_banque_games where room_id=r.id;
  select * into q from app_private.va_banque_questions where id=g.question_id;

  v_show_question := g.phase in (
    'question','main_result','takeover_open','takeover_question',
    'takeover_result','round_result','final_question','final_reveal','finished'
  );
  v_show_solution := g.phase in (
    'main_result','takeover_open','takeover_result','round_result','final_reveal','finished'
  );

  select jsonb_agg(
    jsonb_build_object(
      'id',p.id,
      'name',rp.display_name,
      'avatar',rp.avatar,
      'points',p.points,
      'isConnected',rp.last_seen_at > now()-interval '12 seconds'
    )
    order by p.points desc,rp.joined_at asc
  ) into v_players
  from app_private.va_banque_players p
  join app_private.room_players rp on rp.id=p.player_id
  where p.room_id=r.id;

  if g.phase in ('bid_reveal','tie_bid','tie_reveal','question','main_result','takeover_open','takeover_question','takeover_result','round_result') then
    select jsonb_agg(
      jsonb_build_object(
        'playerId',p.player_id,
        'bid',p.bid,
        'tieBid',case when p.tie_locked then p.tie_bid else null end
      )
      order by rp.joined_at
    ) into v_bids
    from app_private.va_banque_players p
    join app_private.room_players rp on rp.id=p.player_id
    where p.room_id=r.id;
  else
    v_bids:='[]'::jsonb;
  end if;

  if g.phase in ('final_reveal','finished') then
    select jsonb_agg(
      jsonb_build_object(
        'playerId',p.player_id,
        'bid',p.final_bid,
        'answerIndex',p.final_answer_index,
        'correct',p.final_answer_index=q.correct_index
      )
      order by rp.joined_at
    ) into v_final_answers
    from app_private.va_banque_players p
    join app_private.room_players rp on rp.id=p.player_id
    where p.room_id=r.id;
  else
    v_final_answers:='[]'::jsonb;
  end if;

  return jsonb_build_object(
    'serverNow',now(),
    'phase',g.phase,
    'deadline',g.phase_deadline,
    'roundIndex',g.round_index,
    'regularRounds',g.regular_rounds,
    'category',q.category,
    'difficulty',q.difficulty,
    'question',case when v_show_question then q.prompt else null end,
    'options',case when v_show_question then q.options else '[]'::jsonb end,
    'correctIndex',case when v_show_solution then q.correct_index else null end,
    'explanation',case when v_show_solution then q.explanation else null end,
    'players',coalesce(v_players,'[]'::jsonb),
    'bids',coalesce(v_bids,'[]'::jsonb),
    'winningPlayerId',g.winning_player_id,
    'winningBid',g.winning_bid,
    'tiePlayerIds',to_jsonb(g.tie_player_ids),
    'takeoverPlayerId',g.takeover_player_id,
    'takeoverRisk',g.takeover_risk,
    'lastEvent',g.last_event,
    'finalAnswers',coalesce(v_final_answers,'[]'::jsonb),
    'isHost',v_is_host,
    'viewer',case when viewer.id is null then null else jsonb_build_object(
      'id',viewer.id,
      'name',viewer.display_name,
      'avatar',viewer.avatar,
      'points',vp.points,
      'bid',vp.bid,
      'bidLocked',vp.bid_locked,
      'tieBid',vp.tie_bid,
      'tieLocked',vp.tie_locked,
      'answerIndex',vp.answer_index,
      'answerLocked',vp.answer_locked,
      'finalBid',vp.final_bid,
      'finalBidLocked',vp.final_bid_locked,
      'finalAnswerIndex',vp.final_answer_index,
      'finalAnswerLocked',vp.final_answer_locked
    ) end
  );
end;
$$;

create or replace function app_private.submit_va_banque_bid_internal(
  p_code text,p_player_token uuid,p_bid integer
)
returns boolean
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  r app_private.platform_rooms%rowtype;
  g app_private.va_banque_games%rowtype;
  p app_private.va_banque_players%rowtype;
  v_max integer;
  v_min integer;
begin
  perform app_private.va_banque_tick_internal(p_code);

  select * into r from app_private.platform_rooms
  where code=upper(trim(p_code)) and game_slug='va-banque' and status='active' limit 1;
  if r.id is null then raise exception 'Game not found'; end if;

  select * into g from app_private.va_banque_games where room_id=r.id for update;
  if g.phase<>'bidding' or g.phase_deadline<=now() then raise exception 'Bidding closed'; end if;

  select vp.* into p
  from app_private.va_banque_players vp
  join app_private.room_players rp on rp.id=vp.player_id
  where vp.room_id=r.id and rp.player_token=p_player_token
  for update of vp;

  if p.player_id is null then raise exception 'Player not found'; end if;
  if p.bid_locked then raise exception 'Bid already locked'; end if;

  v_max:=greatest(50,floor((p.points*0.5)/50.0)::integer*50);
  v_min:=least(100,v_max);

  if p_bid<>0 and (p_bid<v_min or p_bid>v_max or p_bid%50<>0) then
    raise exception 'Invalid bid';
  end if;

  update app_private.va_banque_players
  set bid=p_bid,bid_locked=true
  where room_id=r.id and player_id=p.player_id;

  perform app_private.va_banque_tick_internal(p_code);
  return true;
end;
$$;

create or replace function app_private.submit_va_banque_tie_bid_internal(
  p_code text,p_player_token uuid,p_bid integer
)
returns boolean
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  r app_private.platform_rooms%rowtype;
  g app_private.va_banque_games%rowtype;
  p app_private.va_banque_players%rowtype;
  v_max integer;
  v_min integer;
begin
  perform app_private.va_banque_tick_internal(p_code);
  select * into r from app_private.platform_rooms
  where code=upper(trim(p_code)) and game_slug='va-banque' and status='active' limit 1;
  select * into g from app_private.va_banque_games where room_id=r.id for update;

  if g.phase<>'tie_bid' or g.phase_deadline<=now() then raise exception 'Tie bidding closed'; end if;

  select vp.* into p
  from app_private.va_banque_players vp
  join app_private.room_players rp on rp.id=vp.player_id
  where vp.room_id=r.id and rp.player_token=p_player_token
  for update of vp;

  if p.player_id is null or not (p.player_id=any(g.tie_player_ids)) then
    raise exception 'Not in tie';
  end if;
  if p.tie_locked then raise exception 'Bid already locked'; end if;

  v_max:=greatest(50,floor((p.points*0.5)/50.0)::integer*50);
  v_min:=g.winning_bid+50;

  if p_bid<>0 and (p_bid<v_min or p_bid>v_max or p_bid%50<>0) then
    raise exception 'Invalid tie bid';
  end if;

  update app_private.va_banque_players
  set tie_bid=p_bid,tie_locked=true
  where room_id=r.id and player_id=p.player_id;

