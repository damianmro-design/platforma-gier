create or replace function app_private.claim_va_banque_takeover_internal(
  p_code text,p_player_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = app_private, pg_temp
as $$
declare
  r app_private.platform_rooms%rowtype;
  g app_private.va_banque_games%rowtype;
  v_player uuid;
  v_points integer;
  v_risk integer;
begin
  perform app_private.va_banque_tick_internal(p_code);

  select * into r from app_private.platform_rooms
  where code=upper(trim(p_code)) and game_slug='va-banque' and status='active' limit 1;

  select * into g
  from app_private.va_banque_games
  where room_id=r.id
  for update;

  if g.phase<>'takeover_open' or g.phase_deadline<=now() or g.takeover_player_id is not null then
    return jsonb_build_object('won',false);
  end if;

  select rp.id,vp.points into v_player,v_points
  from app_private.room_players rp
  join app_private.va_banque_players vp on vp.player_id=rp.id and vp.room_id=r.id
  where rp.room_id=r.id and rp.player_token=p_player_token
  limit 1;

  if v_player is null or v_player=g.winning_player_id then
    return jsonb_build_object('won',false);
  end if;

  v_risk:=least(v_points,greatest(50,round((g.winning_bid*0.5)/50.0)::integer*50));

  update app_private.va_banque_players
  set answer_index=null,answer_locked=false
  where room_id=r.id and player_id=v_player;

  update app_private.va_banque_games
  set takeover_player_id=v_player,takeover_risk=v_risk,
      phase='takeover_question',phase_deadline=now()+interval '12 seconds',
      last_event=jsonb_build_object('type','takeover_claimed','playerId',v_player,'risk',v_risk),
      updated_at=now()
  where room_id=r.id;

  return jsonb_build_object('won',true,'risk',v_risk);
end;
$$;

